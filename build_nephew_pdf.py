class PDF(FPDF):
    def footer(self):
        self.set_y(-14)
        self.set_font("wqy", size=8)
        self.set_text_color(140, 140, 140)
        self.cell(0, 8, f"- {self.page_no()} -", align="C")


def usable_w(pdf):
    return pdf.w - pdf.l_margin - pdf.r_margin


def para(pdf, text, size=10.5, leading=6.2):
    pdf.set_font("wqy", size=size)
    pdf.set_text_color(30, 30, 30)
    width = usable_w(pdf)
    for line in text.split("\n"):
        pdf.set_x(pdf.l_margin)
        if not line.strip():
            pdf.ln(2.5)
            continue
        pdf.multi_cell(width, leading, line)


def bar(pdf, who, when):
    width = usable_w(pdf)
    if who.startswith("用户"):
        pdf.set_fill_color(232, 244, 255)
        pdf.set_text_color(20, 80, 140)
    else:
        pdf.set_fill_color(245, 245, 245)
        pdf.set_text_color(50, 50, 50)
    pdf.set_font("wqy", size=10)
    pdf.ln(3)
    pdf.set_x(pdf.l_margin)
    pdf.cell(width, 8, f"  {who}    {when}", fill=True, new_x=XPos.LMARGIN, new_y=YPos.NEXT)
    pdf.ln(2)


