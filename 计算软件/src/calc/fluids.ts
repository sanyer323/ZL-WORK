export function getFluid(id: string): FluidProps {
  const f = FLUIDS.find((x) => x.id === id)
  if (!f) throw new Error(`未知工质: ${id}`)
  return f
}

export function fluidsByCategory(): { category: FluidCategory; label: string; items: FluidProps[] }[] {
  const order = Object.keys(CATEGORY_LABEL) as FluidCategory[]
  return order
    .map((category) => ({
      category,
      label: CATEGORY_LABEL[category],
      items: FLUIDS.filter((f) => f.category === category),
    }))
    .filter((g) => g.items.length > 0)
}

export function searchFluids(query: string): FluidProps[] {
  const q = query.trim().toLowerCase()
  if (!q) return FLUIDS
  return FLUIDS.filter((f) => {
    const hay = [
      f.id,
      f.name,
      f.nameEn,
      f.cas ?? '',
      ...(f.tags ?? []),
      CATEGORY_LABEL[f.category],
    ]
      .join(' ')
      .toLowerCase()
    return hay.includes(q)
  })
}

/** 理想气体密度修正 ρ = ρ_ref * (P/P_ref) * (T_ref/T) */
export function gasDensity(
  refDensity: number,
  pPa: number,
  tK: number,
  pRef = 101325,
  tRef = 293.15,
): number {
  return refDensity * (pPa / pRef) * (tRef / tK)
}

