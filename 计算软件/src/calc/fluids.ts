export interface FluidProps {
  id: string
  name: string
  nameEn: string
  phase: FluidPhase
  category: FluidCategory
  /** kg/m³ @ 参考态 */
  density: number
  /** Pa·s */
  viscosity: number
  /** 等熵指数 κ */
  kappa?: number
  /** 分子量 g/mol */
  molarMass?: number
  /** 蒸汽压 Pa（液体，气蚀估算） */
  vaporPressure?: number
  /** 临界压力 Pa */
  pc?: number
  /** CAS（可选） */
  cas?: string
  /** 参考说明 */
  note?: string
  tags?: string[]
}

function L(
  partial: Omit<FluidProps, 'phase'> & { phase?: FluidPhase },
): FluidProps {
  return { phase: 'liquid', ...partial }
}

function G(
  partial: Omit<FluidProps, 'phase'> & { phase?: FluidPhase },
): FluidProps {
  return { phase: 'gas', ...partial }
}

function S(
  partial: Omit<FluidProps, 'phase'> & { phase?: FluidPhase },
): FluidProps {
  return { phase: 'steam', ...partial }
}

